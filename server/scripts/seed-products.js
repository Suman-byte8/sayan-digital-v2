async function seed() {
  const rows = [
    ...PRINTING_PRODUCTS.map((p) => ({ ...p, type: "PRINTING" })),
    ...STATIONERY_PRODUCTS.map((p) => ({ ...p, type: "STATIONERY" })),
  ];

  for (const row of rows) {
    await prisma.product.upsert({
      where: { slug: row.slug },
      create: { ...row, stock: 100, isActive: true },
      update: row,
    });
  }

  console.log(`Seeded ${rows.length} products.`);
}

seed()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => process.exit());
